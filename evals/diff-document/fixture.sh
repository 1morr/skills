#!/bin/bash
# 用法：claude plugin eval 帶 --scaffold 時，在每次執行的空工作目錄裡跑這支，寫出兩版假報告。
# 兩版的差異由 skills/diff/scripts/diff.py 算是 2 處（3 段改寫相連算 1 處，一刪一增相鄰算 1 處）；改了內容要重算，graders/ 跟著改。
set -eu

cat > report-v1.md <<'V1'
# 第三季倉庫盤點報告

本報告整理第三季末北區倉庫的盤點結果，供採購會議使用。

盤點在九月二十八日進行，共清點 412 個品項，其中 9 個品項的帳面數量和實際數量不符。

差異最大的是包裝紙箱，帳面 1,200 個，實際只有 1,050 個。

倉管推測差異來自八月的兩次緊急出貨沒有登記。

建議下一季改用掃碼出庫，並在每月月底抽盤二十個品項。

冷藏區的溫度紀錄完整，沒有超出標準的時段。

本次盤點沒有發現過期品。

報告人：倉儲組
V1

cat > report-v2.md <<'V2'
